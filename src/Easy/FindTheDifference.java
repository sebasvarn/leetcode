package Easy;

/*
You are given two strings s and t.

        String t is generated by random shuffling string s and then add one more letter at a random position.

        Return the letter that was added to t.



        Example 1:

        Input: s = "abcd", t = "abcde"
        Output: "e"
        Explanation: 'e' is the letter that was added.
        Example 2:

        Input: s = "", t = "y"
        Output: "y"


            Constraints:

            0 <= s.length <= 1000
            t.length == s.length + 1
         s and t consist of lowercase English letters.*/
public class FindTheDifference {
        public char findTheDifference(String s, String t) {
            int diff = 0; //we use diff to store the difference between the sum of the ASCII values of the characters in t and the sum of the ASCII values of the characters in s
            for (int i = 0; i < s.length(); i++) { //we iterate through the characters in s and t
                diff -= s.charAt(i); //we subtract the ASCII value of the character in s from diff
                diff += t.charAt(i); //we add the ASCII value of the character in t to diff
            }
            diff += t.charAt(s.length()); //we add the ASCII value of the last character in t to diff
            return (char) diff; //we return the character represented by diff
        }

        public static void main(String[] args) {
            FindTheDifference findTheDifference = new FindTheDifference();
            System.out.println(findTheDifference.findTheDifference("abcd", "abcde"));
        }
}



